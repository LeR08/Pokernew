//! Writes data/preflop_matrix.txt: the exact all-in equity of every starting
//! hand class against every other (169 × 169), card removal included.
//!
//! For classes A and B, the equity is the average over every pair of combos
//! (a in A, b in B) that share no card, each enumerated over all 1 712 304
//! boards (ties count half). Pairs that only differ by a renaming of the suits
//! have the same equity, so each distinct pattern is enumerated once.
//!
//! cargo run --release -p lps-equity --example gen_preflop_matrix   (about 15 min on 4 cores)
use std::collections::HashMap;

use lps_equity::combo::{all_combos, Combo, NUM_CLASSES};
use lps_equity::{equity, Mode, Options, Range};
use lps_evaluator::{card, rank_of, suit_of, Card};

fn perms() -> Vec<[u8; 4]> {
    let mut out = Vec::new();
    for a in 0..4u8 {
        for b in 0..4u8 {
            for c in 0..4u8 {
                for d in 0..4u8 {
                    let p = [a, b, c, d];
                    if (0..4).all(|i| (0..4).all(|j| i == j || p[i] != p[j])) {
                        out.push(p);
                    }
                }
            }
        }
    }
    out
}

fn key(a: Combo, b: Combo, perms: &[[u8; 4]]) -> [Card; 4] {
    perms
        .iter()
        .map(|p| {
            let m = |c: Card| card(rank_of(c), p[suit_of(c) as usize]);
            let (x1, x2) = (m(a.hi), m(a.lo));
            let (y1, y2) = (m(b.hi), m(b.lo));
            [x1.max(x2), x1.min(x2), y1.max(y2), y1.min(y2)]
        })
        .min()
        .unwrap()
}

fn main() {
    let perms = perms();
    let by_class: Vec<Vec<Combo>> = (0..NUM_CLASSES)
        .map(|c| {
            all_combos()
                .iter()
                .copied()
                .filter(|x| x.class() == c)
                .collect()
        })
        .collect();
    let opts = Options {
        mode: Mode::Exhaustive,
        ..Options::default()
    };
    let mut cache: HashMap<[Card; 4], f64> = HashMap::new();
    let mut lines = Vec::new();
    for a in 0..NUM_CLASSES {
        let mut row = Vec::new();
        for b in 0..NUM_CLASSES {
            let (mut sum, mut n) = (0.0, 0u32);
            for &x in &by_class[a] {
                for &y in &by_class[b] {
                    if x.mask().0 & y.mask().0 != 0 {
                        continue;
                    }
                    let k = key(x, y, &perms);
                    let e = *cache.entry(k).or_insert_with(|| {
                        equity(&[Range::single(x), Range::single(y)], &[], &[], &opts, None)
                            .unwrap()
                            .players[0]
                            .equity
                    });
                    sum += e;
                    n += 1;
                }
            }
            row.push(format!("{:.6}", sum / n as f64));
        }
        eprintln!("class {a}/169, {} patterns", cache.len());
        lines.push(row.join(" "));
    }
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/data/preflop_matrix.txt");
    std::fs::write(
        path,
        format!(
            "# Exact preflop all-in equity, row class vs column class (grid cells 0..169, see combo.rs), ties count half.\n# Generated by examples/gen_preflop_matrix.rs.\n{}\n",
            lines.join("\n")
        ),
    )
    .unwrap();
    println!("wrote {path} ({} distinct patterns)", cache.len());
}
